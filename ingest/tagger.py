def find_rabbi(t):
    r = _find_rabbi(t)
    return ALIASES.get(r, r)


def _find_rabbi(t):
    m = RABBI_RE.search(t)
    if not m:
        return ""
    words = [w for w in m.group(2).split() if w not in STOP]
    # stop the name where the title moves on to the topic
    name = []
    for w in words:
        w = w.strip('׳"\':?.;!_[]')
        if not w or w in END or re.search(r"[\d_a-zA-Z\[\]]", w):
            break
        if w.startswith(("ו", "ל", "ב")) and len(name) >= 2:
            break
        name.append(w)
        if len(name) >= 2 and name[-1] not in ("בן", "בר"):
            break
    if not name:
        return ""
    prefix = "פרופ'" if m.group(1).startswith("פרופ") else "הרב"
    full = f"{prefix} {' '.join(name)}"
    if full in SUBJECTS or any(full.startswith(x + " ") for x in SUBJECTS):
        return ""
    return full


def find_topic(t):
    for topic, keys in TOPICS:
        if any(k in t for k in keys):
            return topic
    return "אמונה ומחשבה"


def tag(title):
    t = clean_title(title)
    return {"t": t, "r": find_rabbi(t), "c": find_topic(t)}


def to_minutes(d):
    parts = [int(p) for p in d.split(":")]
    secs = 0
    for p in parts:
        secs = secs * 60 + p
    return max(1, round(secs / 60))
