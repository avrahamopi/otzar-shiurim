def clean_title(t):
    t = re.sub(r"#(?!\d)\S+", "", t)              # hashtags (keep "#5" lesson numbers)
    t = re.sub(r"\s+I\s+", " | ", t)              # "I" used as a separator
    t = re.sub(r"\s*\|\|\s*", " | ", t)
    t = re.sub(r"\s*\|\s*ישיבת [^|]+$", "", t)     # trailing "| ישיבת X"
    t = re.sub(r"\s*\|\s*$", "", t)
    return re.sub(r"\s{2,}", " ", t).strip(" |")


